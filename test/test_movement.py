def test_linear_x_blockage():
    lst = [Block.block(0, 63, 0), Block.block(-3, 63, 3), Block.block(-3, 65, 4), Block.block(-5, 65, 3), Block.block(-5, 63, 5)]
    c = Course(lst)
    p = Player(c, 0.5, 64.0, -0.3)
    p.move_w_sprint(45.0, False)
    print(f"(x, y, z): ({p.x}, {p.y}, {p.z})")
    for i in range(0, 5):
        p.move_w_sprint(0.0, False)
        print(f"(x, y, z): ({p.x}, {p.y}, {p.z})")
    for i in range(6, 29):
        p.move_w_sprint(0.0, True)
        print(f"(x, y, z): ({p.x}, {p.y}, {p.z})")
    
    assert p.x == -4.080896650891273
    assert p.y == 64.10408037809304
    assert p.z == 5.883105574354205


